import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {createRequire} from 'node:module';
const require = createRequire('C:/Users/luisi/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/review.cjs');
const {chromium} = require('playwright');
const scratch = path.join(process.cwd(), '.pytest_tmp/reporting_verification');
const label = process.argv[2] ?? 'browser_check';
const fixture = JSON.parse(fs.readFileSync(path.join(scratch,'browser_fixture.json'),'utf8'));
const checks = [], errors = [], requests = [];
const check = (name, passed, detail=null) => {checks.push({name,passed,detail});};
const browser = await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const page = await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
page.on('pageerror',error=>errors.push(error.message));
await page.route(/https?:\/\//,route=>{requests.push(route.request().url());return route.abort();});
try {
  await page.goto(pathToFileURL(path.join(scratch,'browser_report.html')).href);
  await page.locator('#study-0 .variant:not([hidden]) .js-plotly-plot').waitFor();
  check('six_studies',await page.locator('details.study').count()===6);
  const loadedInitially = await page.locator('.plot[data-loaded]').evaluateAll(nodes=>nodes.map(el=>({study:el.closest('.study').id, studyOpen:el.closest('.study').open, foldHidden:el.closest('.variant').hidden})));
  check('only_initial_visible_plot_initialized',loadedInitially.length===1,loadedInitially);
  check('initial_fold_rows', (await page.locator('#study-0 .variant:not([hidden]) .scope').innerText()).includes('8 rows'));
  await page.locator('#study-0 .fold-selector').selectOption('1');
  await page.locator('#study-0 .variant[data-fold="1"] .js-plotly-plot').waitFor();
  check('fold_switch_rows',(await page.locator('#study-0 .variant:not([hidden]) .scope').innerText()).includes('14 rows'));
  check('histogram_and_kde',await page.locator('#study-0 .variant:not([hidden]) .js-plotly-plot').evaluate(el=>el.data.length===2 && el.data[0].type==='bar' && el.data[1].type==='scatter'));
  await page.screenshot({path:path.join(scratch,label+'_distribution.png')});

  await page.locator('nav a[href="#study-1"]').click();
  check('signed_bars',await page.locator('#study-1 .variant:not([hidden]) .bar.positive').count()>0 && await page.locator('#study-1 .variant:not([hidden]) .bar.negative').count()>0);
  const metric = page.locator('#study-1 .variant:not([hidden]) .leaderboard');
  const table = page.locator('#study-1 .variant:not([hidden]) table').first();
  const sorter = table.locator('th button').filter({hasText:'first · pearson ↕'}).first();
  await sorter.click();
  const values = await table.locator('tbody tr').evaluateAll(rows=>rows.map(row=>row.cells[3].dataset.value));
  const finite = values.filter(x=>x!=='').map(x=>Math.abs(Number(x)));
  check('coefficient_sort_descending',finite.every((x,i)=>i===0 || finite[i-1]>=x),values);
  check('missing_sort_last',values.slice(0,finite.length).every(x=>x!=='') && values.slice(finite.length).every(x=>x===''));
  await sorter.click();
  const asc = (await table.locator('tbody tr').evaluateAll(rows=>rows.map(row=>row.cells[3].dataset.value))).filter(x=>x!=='').map(x=>Math.abs(Number(x)));
  check('coefficient_sort_ascending',asc.every((x,i)=>i===0 || asc[i-1]<=x));
  await page.screenshot({path:path.join(scratch,label+'_associations.png')});

  await page.getByRole('button',{name:'Collapse studies',exact:true}).click();
  check('collapse',await page.locator('details.study[open]').count()===0);
  await page.getByRole('button',{name:'Expand studies',exact:true}).click();
  check('expand',await page.locator('details.study[open]').count()===6);
  await page.locator('#study-search').fill('timeline');
  check('search_filters_studies',await page.locator('details.study:not([hidden])').count()===1);
  check('search_filters_navigation',await page.locator('nav a:not([hidden])').count()===1);
  await page.locator('#study-search').fill('');
  await page.locator('nav a[href="#study-2"]').click();
  const timeline = page.locator('#study-2 .js-plotly-plot');
  await timeline.waitFor();
  check('two_exact_entities',await timeline.evaluate(el=>el.data.length===2 && el.data.every(t=>t.name.includes('922337203685477'))));
  await page.locator('#study-2 .updatemenu-header').first().click();
  await page.locator('#study-2 .updatemenu-dropdown-button').nth(1).click();
  check('entity_dropdown',await timeline.evaluate(el=>el.data.filter(t=>t.visible!==false).length===1));
  const point = page.locator('#study-2 .scatterlayer .point').first();
  await timeline.scrollIntoViewIfNeeded();
  const pointBox = await point.boundingBox();
  await page.mouse.move(pointBox.x+pointBox.width/2,pointBox.y+pointBox.height/2);
  await page.locator('#study-2 .hoverlayer .hovertext').first().waitFor();
  check('hover_tooltip',await page.locator('#study-2 .hoverlayer .hovertext').count()>0);
  const beforeZoom = await timeline.evaluate(el=>JSON.stringify(el._fullLayout.xaxis.range));
  const box = await page.locator('#study-2 .nsewdrag').boundingBox();
  await page.mouse.move(box.x+box.width*.15,box.y+box.height*.3);
  await page.mouse.down();
  await page.mouse.move(box.x+box.width*.7,box.y+box.height*.8,{steps:8});
  await page.mouse.up();
  await page.waitForFunction(before=>JSON.stringify(document.querySelector('#study-2 .js-plotly-plot')._fullLayout.xaxis.range)!==before,beforeZoom);
  check('drag_zoom',true);
  await page.screenshot({path:path.join(scratch,label+'_timeline.png')});
  const downloadTitle = (await page.locator('#study-2 .modebar [data-title]').evaluateAll(nodes=>nodes.map(el=>el.dataset.title))).find(title=>title.startsWith('Download plot'));
  const svgPromise = page.waitForEvent('download');
  await page.locator(`#study-2 .modebar [data-title="${downloadTitle}"]`).click();
  const svg = await svgPromise;
  await svg.saveAs(path.join(scratch,label+'_export.svg'));
  check('svg_export',svg.suggestedFilename().endsWith('.svg') && fs.readFileSync(path.join(scratch,label+'_export.svg'),'utf8').includes('<svg'));

  await page.locator('nav a[href="#study-3"]').click();
  const idTable = page.locator('#study-3 table').first();
  await idTable.locator('th button').first().click();
  const orderedIds = await idTable.locator('tbody tr').evaluateAll(rows=>rows.map(row=>row.cells[0].dataset.value));
  check('exact_uint64_sorting',JSON.stringify(orderedIds)===JSON.stringify(fixture.exact_ids_descending),{actual:orderedIds,expected:fixture.exact_ids_descending});
  check('escaped_labels_do_not_execute',await page.evaluate(()=>window.evil===undefined && !document.querySelector('img[onerror]')));
  check('trusted_custom_renderer',await page.locator('#custom-renderer').count()===1);
  const fullPanel = page.locator('#study-3 details').filter({has:page.locator('summary').filter({hasText:'Data: full (205 rows)'})}).last();
  await fullPanel.locator('summary').click();
  const csvPromise = page.waitForEvent('download');
  await fullPanel.locator('a.download').click();
  const csv = await csvPromise;
  await csv.saveAs(path.join(scratch,label+'_export.csv'));
  check('full_csv_export',fs.readFileSync(path.join(scratch,label+'_export.csv'),'utf8').trim().split(/\r?\n/).length===206);
  check('table_preview_capped',await fullPanel.locator('tbody tr').count()===200);

  await page.goto(pathToFileURL(path.join(scratch,'browser_iframe.html')).href);
  const embedded = page.frameLocator('iframe');
  await embedded.locator('#study-0 .js-plotly-plot').first().waitFor();
  await embedded.locator('#study-0 .fold-selector').selectOption('1');
  check('native_iframe_fold_interaction',(await embedded.locator('#study-0 .variant:not([hidden]) .scope').innerText()).includes('14 rows'));
  check('iframe_style_and_script_isolation',await page.evaluate(()=>getComputedStyle(document.querySelector('#parent-heading')).color==='rgb(255, 0, 0)' && window.Plotly===undefined));
  await page.screenshot({path:path.join(scratch,label+'_iframe.png')});
} catch(error) {
  errors.push(error.stack);
} finally {
  await browser.close();
}
check('offline_no_remote_requests',requests.length===0,requests);
check('no_browser_errors',errors.length===0,errors);
const record={checked_at_utc:new Date().toISOString(),fixture,checks,errors,status:checks.every(x=>x.passed)?'passed':'failed'};
const output=path.join(scratch,label+'.json');
if(fs.existsSync(output))throw Error('Preserve existing browser evidence.');
fs.writeFileSync(output,JSON.stringify(record,null,2)+'\n');
console.log(JSON.stringify({status:record.status,checks:checks.length,failures:checks.filter(x=>!x.passed)},null,2));
if(record.status!=='passed')process.exitCode=1;
